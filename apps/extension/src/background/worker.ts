/**
 * Wires the service worker: storage -> clock -> config -> ports -> engine -> sync -> learning -> runtime handlers
 * -> commands, plus the install / update / startup lifecycle. `createWorker` registers every chrome listener
 * synchronously (MV3 requires listeners at the top level of the first turn); handlers await `core.ready`.
 */
import { createCore, type CoreDeps, type CoreWithActivity } from './core';
import { createHub, type Hub } from './ports';
import { registerCommands } from './commands';
import { registerRuntimeHandlers } from './runtime';
import { ALARM_SWEEP } from './sync/client';

export interface Worker {
  core: CoreWithActivity;
  hub: Hub;
  /** Resolves once state is loaded and startup work (stale in-flight requests, alarms) is done. */
  ready: Promise<void>;
  /** Exposed for tests. */
  onInstalled(details: { reason: string; previousVersion?: string }): Promise<void>;
  onStartup(): Promise<void>;
}

export const CONTENT_SCRIPT_FILE = 'content/content-script.js';
export const WELCOME_PATH = 'options/options.html#welcome';

export function createWorker(deps: CoreDeps): Worker {
  const c = deps.chrome;
  const core = createCore(deps) as CoreWithActivity;
  const hub = createHub(core, c);

  // Listeners first, synchronously.
  hub.attach();
  registerRuntimeHandlers({ core, hub, chrome: c });
  registerCommands({ core, hub, chrome: c });

  try {
    const r = c?.sidePanel?.setPanelBehavior?.({ openPanelOnActionClick: false });
    if (r instanceof Promise) r.catch(() => undefined);
  } catch {
    // older Chrome
  }

  const reinjectContentScripts = async (): Promise<void> => {
    if (!c?.tabs?.query || !c.scripting?.executeScript) return;
    let tabs: chrome.tabs.Tab[] = [];
    try {
      tabs = await c.tabs.query({ url: ['http://*/*', 'https://*/*'] });
    } catch {
      return;
    }
    await Promise.all(
      tabs.map(async (tab) => {
        if (typeof tab.id !== 'number') return;
        try {
          await c.scripting.executeScript({ target: { tabId: tab.id, allFrames: true }, files: [CONTENT_SCRIPT_FILE] });
        } catch {
          // chrome:// pages, the Web Store, tabs without permission: ignore per-tab errors
        }
      }),
    );
  };

  const onInstalled = async (details: { reason: string; previousVersion?: string }): Promise<void> => {
    await core.ready;
    if (details.reason === 'install') {
      // Device id and user salt are generated by core.ready; open the welcome page.
      try {
        await c?.tabs?.create({ url: c.runtime.getURL(WELCOME_PATH) });
      } catch (err) {
        console.debug('[jammarly] could not open the welcome page', err);
      }
      return;
    }
    if (details.reason === 'update') {
      core.cache.clear();
      await reinjectContentScripts();
    }
  };

  const onStartup = async (): Promise<void> => {
    await core.ready;
    const stale = core.inflightRecords();
    if (stale.length > 0) {
      hub.rememberStaleInflight(stale);
      await core.clearInflight();
    }
  };

  c?.runtime?.onInstalled.addListener((details) => {
    void onInstalled(details).catch((err) => console.debug('[jammarly] onInstalled failed', err));
  });
  c?.runtime?.onStartup.addListener(() => {
    void onStartup().catch((err) => console.debug('[jammarly] onStartup failed', err));
  });
  c?.alarms?.onAlarm.addListener((alarm) => {
    void core.ready.then(async () => {
      if (alarm.name === ALARM_SWEEP) await core.sweepDismissals();
      else await core.sync.handleAlarm(alarm.name);
    });
  });

  // A cold start (not only chrome's onStartup) also surfaces requests left in flight by a terminated worker.
  const ready = core.ready.then(onStartup);

  return { core, hub, ready, onInstalled, onStartup };
}
